#!/usr/bin/env python3
"""Verify every number in chapter 18-11 (hardware security), its problems and its lab.

Independent routes:
- the AES S-box generated by the lab is checked against FIPS 197's worked values and for being a permutation;
- brute-force, glitch and honeypot figures by direct arithmetic;
- the timing attack and CPA by the lab's simulations (fixed seeds), with the query counts also derived by formula;
- the CPA correlation by formula and by measuring it on simulated traces;
- PUF failure by the binomial formula, by an independent survival-function computation (scipy), and by Monte Carlo;
- the host C comparison test by compiling and running it.
"""
from __future__ import annotations

import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from scipy.stats import binom

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
LAB = ROOT / "labs" / "18-11-lab"
sys.path.insert(0, str(HERE.parents[2] / "tools"))
sys.path.insert(0, str(LAB))
from eeverify import Verifier  # noqa: E402
import hwsec as hs  # noqa: E402

v = Verifier.from_files("18-11", ROOT / "chapters" / "18-11-hardware-security.md",
                        ROOT / "solutions" / "18-11-solutions.md", LAB / "README.md")

YEAR = 365.25 * 86400


def rho(sigma):
    return math.sqrt(2 / (2 + sigma ** 2))


def key_fail(p, n, k):
    pbit = binom.sf(n // 2, n, p)          # P(more than n/2 flips)
    return 1 - (1 - pbit) ** k


def smallest_n(p, target, k):
    n = 1
    while key_fail(p, n, k) > target:
        n += 2
    return n


# ---------------------------------------------------------------- S-box
sb = hs.aes_sbox()
v.assert_true("S-box is a permutation", sorted(sb.tolist()) == list(range(256)))
v.assert_true("FIPS 197 values S(0x00)=0x63, S(0x01)=0x7C, S(0x53)=0xED, S(0xFF)=0x16",
              (sb[0x00], sb[0x01], sb[0x53], sb[0xFF]) == (0x63, 0x7C, 0xED, 0x16))
v.check("Lab 18-11.a", int(sb[0x00]))
v.check("Lab 18-11.b", int(sb[0x53]))

# ---------------------------------------------------------------- Example 1
v.check("Ex 18-11.1a", (2 ** 128 + 1) / 2 / 1e12 / YEAR)
v.check("Ex 18-11.1b", (2 ** 32 + 1) / 2 / 1000 / 86400)
v.check("Ex 18-11.1c", 100 * 10 / 10000)

# ---------------------------------------------------------------- Example 2 (timing)
v.check("Ex 18-11.2a", 15 * 256 * 200 + 256)
secret = bytes([0x3A, 0x91, 0x07, 0xEE])
got, q = hs.timing_attack(secret)
v.assert_true("timing attack recovers the 4-byte secret", got == secret, got.hex())
v.check("Ex 18-11.2b", q)
v.assert_true("query count = 3 x 256 x 200 + position of the last byte + 1", q == 3 * 256 * 200 + 0xEE + 1)
got_ct, _ = hs.timing_attack(secret, compare=hs.constant_time)
v.assert_true("constant-time comparison defeats it", got_ct != secret)

# ---------------------------------------------------------------- Example 3 (CPA)
for ident_r, ident_n, s in (("Ex 18-11.3a", "Ex 18-11.3b", 3), ("Ex 18-11.3c", "Ex 18-11.3d", 6)):
    v.check(ident_r, rho(s))
    v.check(ident_n, (4.5 / rho(s)) ** 2)
p_, l_ = hs.simulate_traces(0x2B, 200000, 3.0, seed=180113)
meas = np.corrcoef(hs.HW[sb[p_ ^ 0x2B]], l_)[0, 1]
v.assert_true("measured correlation on simulated traces matches sqrt(2/(2+sigma^2))", abs(meas - rho(3)) < 0.005, f"{meas:.4f}")
for s in (1, 3, 6):
    p_, l_ = hs.simulate_traces(0x2B, 2000, s)
    v.assert_true(f"CPA recovers the key with 2000 traces at noise {s}", hs.cpa_rank(p_, l_, 0x2B)[1] == 0)
pm, lm = hs.simulate_traces(0x2B, 20000, 1, masked=True)
best, rank, r_true = hs.cpa_rank(pm, lm, 0x2B)
v.check("Ex 18-11.3e", r_true)
v.check("Ex 18-11.3f", rank)
v.assert_true("masked correlation is within noise of zero", abs(r_true) < 4 / math.sqrt(20000))

# ---------------------------------------------------------------- Example 4 (PUF)
n_a, n_b = smallest_n(0.05, 1e-6, 128), smallest_n(0.205, 1e-6, 128)
v.check("Ex 18-11.4a", n_a)
v.check("Ex 18-11.4b", n_b)
v.assert_true("lab smallest_repetition agrees", hs.smallest_repetition(0.05, 1e-6) == n_a and hs.smallest_repetition(0.205, 1e-6) == n_b)
v.check("Ex 18-11.4c", 128 * n_a)
v.check("Ex 18-11.4d", 128 * n_b)
v.check("Ex 18-11.4e", key_fail(0.15, 9, 128))
v.check("Ex 18-11.4f", hs.simulate_puf(0.15, 9))
v.assert_true("each bit fails about once in 180 at p = 0.15, n = 9", abs(1 / binom.sf(4, 9, 0.15) - 178) < 2)

# ---------------------------------------------------------------- Examples 5 and 6
v.check("Ex 18-11.5a", 1 / (1e-4 * 10))
v.check("Ex 18-11.5b", 1 / (1e-8 * 10) / 86400)
v.check("Ex 18-11.6a", 50000 / 1e6)
v.check("Ex 18-11.6b", 50000)
v.check("Ex 18-11.6c", 24)
v.check("Ex 18-11.6d", 72)

# ---------------------------------------------------------------- Problems
v.check("18-11.1a", (2 ** 20 + 1) / 2 / 100 / 60)
v.check("18-11.1b", 36 ** 6)
v.check("18-11.1c", (36 ** 6 + 1) / 2 / 1000 / 86400)
v.check("18-11.2a", 7 * 256 * 50 + 256)
ns = {}
for (ir, iN), s in zip((("18-11.3a", "18-11.3b"), ("18-11.3c", "18-11.3d"), ("18-11.3e", "18-11.3f")), (2, 4, 8)):
    v.check(ir, rho(s))
    ns[s] = (5 / rho(s)) ** 2
    v.check(iN, ns[s])
v.check("18-11.3g", ns[4] / ns[2])
v.check("18-11.3h", ns[8] / ns[4])
v.assert_true("doubling factor tends to 4", abs((5 / rho(1e3)) ** 2 / (5 / rho(5e2)) ** 2 - 4) < 1e-3)
n4 = smallest_n(0.10, 1e-6, 256)
v.check("18-11.4a", n4)
v.check("18-11.4b", 256 * n4)
v.check("18-11.4c", key_fail(0.10, n4, 256))
v.check("18-11.4d", key_fail(0.10, n4 - 2, 256))
v.check("18-11.5a", 1 / (1e-5 * 50) / 60)
v.check("18-11.5b", 1 / (1e-10 * 50) / YEAR)
v.check("18-11.6a", 200000 / 100000)
v.check("18-11.6b", 200000)
v.check("18-11.6c", 5)
v.check("18-11.6d", 24)
v.check("18-11.7a", 100 * 1000 * 50 / 64e6)
v.check("18-11.9a", (1e6 + 1) / 2 / 5 / 60 / 24)
v.check("18-11.10a", 16)
v.check("18-11.10b", (4.5 / (rho(3) / 16)) ** 2)
v.check("18-11.10c", 16 ** 2)

# ---------------------------------------------------------------- lab
v.check("Lab 18-11.c", hs.smallest_repetition(0.15, 1e-6))
v.check("Lab 18-11.d", (4.5 / rho(1)) ** 2)
v.assert_true("lab's tested trace counts: first rank 0 at 30, 100 and 1000", all(
    [hs.cpa_rank(*hs.simulate_traces(0x2B, n, s), 0x2B)[1] for n in (10, 30, 100, 300, 1000)].index(0) == idx
    for s, idx in ((1, 1), (3, 2), (6, 4))))
v.assert_true("too few measurements break the timing attack", hs.timing_attack(secret, reps=20)[0] != secret)

cc = shutil.which("cc") or shutil.which("clang") or shutil.which("gcc")
if not cc:
    sys.exit("verify_18_11: a C compiler is required (see SETUP.md)")
with tempfile.TemporaryDirectory(prefix="v1811_") as td:
    subprocess.run([cc, "-std=c17", "-O1", "-o", f"{td}/t", str(LAB / "c" / "ctcompare_test.c")], check=True,
                   capture_output=True, text=True)
    out = subprocess.run([f"{td}/t"], capture_output=True, text=True).stdout
v.assert_true("host constant-time comparison test passes", "TEST PASSED" in out, out)

# ---------------------------------------------------------------- audit additions
from scipy.stats import norm  # noqa: E402
rng = np.random.default_rng(18110)
mx = np.abs(rng.normal(size=(4000, 255))).max(axis=1).mean()
v.assert_true("expected maximum of 255 |N(0,1)| is about 3", 2.8 < mx < 3.2, f"{mx:.2f}")
hw_true = hs.HW[sb[np.arange(256) ^ 0x2B]]
ghost = max(abs(np.corrcoef(hw_true, hs.HW[sb[np.arange(256) ^ k]])[0, 1]) for k in range(256) if k != 0x2B)
v.assert_true("ghost peaks reach about a quarter of the right key's correlation", 0.15 < ghost < 0.3, f"{ghost:.3f}")
n111 = int(round((4.5 / rho(3)) ** 2))
succ = np.mean([hs.cpa_rank(*hs.simulate_traces(0x2B, n111, 3.0, seed=50000 + s_), 0x2B)[1] == 0 for s_ in range(150)])
v.assert_true("the (4.5/rho)^2 rule succeeds roughly 90% of the time at sigma = 3", 0.8 <= succ <= 0.99, f"{succ:.2f}")
z4 = norm.isf(1e-4)
v.assert_true("Mangard: 3 + 8 z^2 / ln^2((1 + rho)/(1 - rho)) is about 28/rho^2 for small rho",
              abs((3 + 8 * z4 ** 2 / math.log((1 + 0.05) / (1 - 0.05)) ** 2) * 0.05 ** 2 / 28 - 1) < 0.02)
v.assert_true("a 6-digit passkey is 20 bits, one bit per failed pairing", math.ceil(math.log2(999999 + 1)) == 20)
v.assert_true("Solution 10(b): 256 x 4.5^2 x 11/2 = 28 512", 256 * 4.5 ** 2 * 11 / 2 == 28512)
sys.exit(v.finish())
