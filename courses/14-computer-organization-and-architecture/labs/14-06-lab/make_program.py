#!/usr/bin/env python3
"""Build program.hex, data.hex and expected.vh for the pipelined core's testbench (Lab 14-06).

Same program and data as Lab 14-05. The expected cycle count comes from the hazard model of chapter 14-06,
applied to the Python simulator's dynamic trace: cycles = N + 4 + S + 2T, where N is the number of instructions
executed (here including the final EBREAK, which must reach WB), S the number of load-use stalls (a load
followed immediately by an instruction that reads its destination) and T the number of taken branches and jumps.
Run from this directory:  python make_program.py   (the outputs are committed, so CI does not need LLVM).
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "verify"))
from _rv32 import Sim, build  # noqa: E402

ARRAY = [7 * i - 20 for i in range(10)]
USES = {0x33: (1, 1), 0x13: (1, 0), 0x03: (1, 0), 0x23: (1, 1), 0x63: (1, 1), 0x67: (1, 0),
        0x6F: (0, 0), 0x37: (0, 0), 0x17: (0, 0), 0x73: (0, 0)}


def hazard_model(words: list[int], pcs: list[int]) -> dict:
    """Count load-use stalls and taken control transfers along the executed path (pcs, in order)."""
    stalls = taken = 0
    for k, pc in enumerate(pcs):
        w = words[pc // 4]
        op = w & 0x7F
        if op in (0x6F, 0x67) or (op == 0x63 and k + 1 < len(pcs) and pcs[k + 1] != pc + 4):
            taken += 1
        if op == 0x03 and k + 1 < len(pcs):
            nxt = words[pcs[k + 1] // 4]
            u1, u2 = USES[nxt & 0x7F]
            rd = w >> 7 & 31
            if rd and ((u1 and (nxt >> 15 & 31) == rd) or (u2 and (nxt >> 20 & 31) == rd)):
                stalls += 1
    return dict(stalls=stalls, taken=taken)


def generate(outdir: Path = HERE, source: str | None = None) -> dict:
    mem, syms, entry, size = build({"program.s": source or (HERE / "program.s").read_text()}, text=0)
    words = [int.from_bytes(bytes(mem[a + k] for k in range(4)), "little") for a in range(0, size, 4)]
    data = {0x2000 + 4 * i + k: (v & 0xFFFFFFFF) >> 8 * k & 0xFF for i, v in enumerate(ARRAY) for k in range(4)}
    sim = Sim({**mem, **data}, entry)
    trace: list = []
    wtrace: list = []
    n = sim.run(trace=trace, wtrace=wtrace)
    pcs = [pc for pc, _ in trace] + [sim.pc]          # include the EBREAK, which the simulator stops on
    h = hazard_model(words, pcs)
    ninstr = n + 1
    cycles = ninstr + 4 + h["stalls"] + 2 * h["taken"]
    res = [int.from_bytes(bytes(sim.mem.get(a + k, 0) for k in range(4)), "little") for a in (0x100, 0x104)]
    if source is None:
        padded = words + [0x00100073] * (1024 - len(words))
        (outdir / "program.hex").write_text("".join(f"{w:08x}\n" for w in padded))
        dwords = [0] * 0x1000
        for i, v in enumerate(ARRAY):
            dwords[0x2000 // 4 + i] = v & 0xFFFFFFFF
        (outdir / "data.hex").write_text("".join(f"{w:08x}\n" for w in dwords))
        (outdir / "expected.vh").write_text(
            "// Generated by make_program.py from program.s: do not edit.\n"
            f"`define EXPECT_SUM     32'd{res[0]}\n"
            f"`define EXPECT_FIB     32'd{res[1]}\n"
            f"`define EXPECT_INSTR   {ninstr}\n"
            f"`define EXPECT_WRITES  {len(wtrace)}\n"
            f"`define EXPECT_STALLS  {h['stalls']}\n"
            f"`define EXPECT_FLUSHES {h['taken']}\n"
            f"`define EXPECT_CYCLES  {cycles}\n")
    return dict(words=words, sum=res[0], fib=res[1], instr=ninstr, wtrace=wtrace, cycles=cycles, pcs=pcs, **h)


if __name__ == "__main__":
    r = generate()
    print(f"{r['instr']} instructions (with EBREAK), {r['stalls']} load-use stalls, {r['taken']} taken branches/jumps, "
          f"{r['cycles']} cycles predicted; sum = {r['sum']}, fib = {r['fib']}")
