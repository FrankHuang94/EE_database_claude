#!/usr/bin/env python3
"""Build program.hex, data.hex and expected.vh for the single-cycle core's testbench (Lab 14-05).

Assembles and links program.s with LLVM (llvm-mc, ld.lld) at address 0, writes the code as one 32-bit word
per line, writes the array a[i] = 7i - 20 (i = 0..9) at data address 0x2000, runs the program on the course's
RV32I simulator (verify/_rv32.py), and writes the expected results and instruction count for the testbench.
Run from this directory:  python make_program.py   (the outputs are committed, so CI does not need LLVM).
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "verify"))
from _rv32 import Sim, build  # noqa: E402

ARRAY = [7 * i - 20 for i in range(10)]


def generate(outdir: Path = HERE) -> dict:
    mem, syms, entry, size = build({"program.s": (HERE / "program.s").read_text()}, text=0)
    assert entry == 0
    words = [int.from_bytes(bytes(mem[a + k] for k in range(4)), "little") for a in range(0, size, 4)]
    data = {0x2000 + 4 * i + k: (v & 0xFFFFFFFF) >> 8 * k & 0xFF for i, v in enumerate(ARRAY) for k in range(4)}
    sim = Sim({**mem, **data}, entry)
    wtrace: list = []
    n = sim.run(wtrace=wtrace)
    res1 = int.from_bytes(bytes(sim.mem.get(0x100 + k, 0) for k in range(4)), "little")
    res2 = int.from_bytes(bytes(sim.mem.get(0x104 + k, 0) for k in range(4)), "little")
    padded = words + [0x00100073] * (1024 - len(words))  # fill the rest of instruction memory with EBREAK
    (outdir / "program.hex").write_text("".join(f"{w:08x}\n" for w in padded))
    dwords = [0] * 0x1000
    for i, v in enumerate(ARRAY):
        dwords[0x2000 // 4 + i] = v & 0xFFFFFFFF
    (outdir / "data.hex").write_text("".join(f"{w:08x}\n" for w in dwords))
    (outdir / "expected.vh").write_text(
        "// Generated by make_program.py from program.s: do not edit.\n"
        f"`define EXPECT_SUM    32'd{res1}\n"
        f"`define EXPECT_FIB    32'd{res2}\n"
        f"`define EXPECT_CYCLES {n}\n"
        f"`define EXPECT_WRITES {len(wtrace)}\n")
    return dict(words=words, sum=res1, fib=res2, count=n, wtrace=wtrace, syms=syms, size=size)


if __name__ == "__main__":
    r = generate()
    print(f"{len(r['words'])} instruction words; sum = {r['sum']}, fib = {r['fib']}, "
          f"{r['count']} instructions, {len(r['wtrace'])} register writes")
