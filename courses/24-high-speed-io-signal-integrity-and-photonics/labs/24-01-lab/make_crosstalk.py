"""Regenerate crosstalk.cir: a coupled-line ladder for Example 24-01.7."""
import math

N, ELL, Z0, C0 = 200, 50e-3, 50.0, 2.998e8
V = C0 / math.sqrt(3.0)
L, C = Z0 / V, 1 / (Z0 * V)
CM_C, LM_L = 0.04, 0.06


def main(path="crosstalk.cir"):
    dz = ELL / N
    ls, cs = L * dz, C * dz
    cm, cg = CM_C * cs, cs - CM_C * cs
    k = "key:../../chapters/24-01-signal-integrity-fundamentals.md#"
    lines = ["* 24-01 lab: near- and far-end crosstalk on a coupled microstrip pair (Example 24-01.7)",
             "* A 200-section lumped ladder of two 50 ohm lines, 50 mm long, eps_eff = 3.0,",
             f"* L' = {L:.6e} H/m and C' = {C:.6e} F/m per line, Cm/C = {CM_C}, Lm/L = {LM_L}.",
             "* The aggressor is driven through 50 ohm (launching 0.4 V, 30 ps ramp); all four ends see 50 ohm.",
             "* Generated by make_crosstalk.py in this folder; edit that, not this file.",
             f"* EXPECT next {k}Ex_24-01.7d scale=1e-3 rtol=0.005",
             f"* EXPECT farea {k}Ex_24-01.7g scale=1e-12 rtol=0.002",
             "Va src 0 PWL(0 0 50p 0 80p 0.8 2n 0.8)", "Ras src a0 50", "Rvn 0 v0 50"]
    for i in range(N):
        lines += [f"La{i} a{i} a{i+1} {ls:.6e}", f"Lv{i} v{i} v{i+1} {ls:.6e}", f"K{i} La{i} Lv{i} {LM_L}",
                  f"Cag{i} a{i+1} 0 {cg:.6e}", f"Cvg{i} v{i+1} 0 {cg:.6e}", f"Cm{i} a{i+1} v{i+1} {cm:.6e}"]
    lines += [f"Raf a{N} 0 50", f"Rvf v{N} 0 50", ".control", "tran 0.2p 1.2n",
              f"linearize v(v{N}) v(v0) v(a0)", "meas tran next find v(v0) at=500p",
              f"meas tran fext min v(v{N})", f"meas tran farea integ v(v{N}) from=0 to=1.15n",
              "print next fext farea", ".endc", ".end"]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
