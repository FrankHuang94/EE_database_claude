#!/usr/bin/env python3
"""Write the corner netlists for the C1 option B buck converter and, with --run, simulate them and write results.md.

Averaged model (buck_avg.sub), for the loop and the load step:
  loop_vNN.cir  one per input voltage (3.0, 3.6, 4.2 V); ten converters each: five (L, C) combinations, each at
                light load and room temperature (0.1 A, 27 degC on-resistance: the least damping) and at full load
                and hot (1 A, on-resistance +40%). Each measures the DC output, and, through a series injection
                source, the loop gain T = -v(out)/v(fbin): crossover, phase margin, gain margin.
  step_avg.cir  a 0.1 -> 0.6 A step in 100 ns at each input voltage, for nominal (L, C) and for L +20% with
                C -20% (the lowest crossover with the least capacitance): deviation and recovery to within 1%.
Switching model (buck_sw.sub), started from zero with uic and measured after it settles:
  sw_eff_*.cir  3.6 V, nominal parts, 27 degC, at 0.1, 0.5 and 1 A: output voltage and efficiency.
  sw_ripple.cir 4.2 V, 1 A, L -20%, C -20%: output ripple over one period and the peak inductor current.
  sw_step_vNN.cir  each input voltage, nominal parts: the same load step, as a check on the averaged model;
                sw_step_v30_lpcm.cir repeats it at 3.0 V with L +20% and C -20%, the worst combination for the step.
Every measurement is tied to results.md by an EXPECT line, so CI (tools/run_spice.py) re-runs them all.

Usage:  python gen_buck.py          # rewrite the netlists from the published values (tolerances only)
        python gen_buck.py --run    # rewrite, simulate with ngspice and rewrite results.md
"""
from __future__ import annotations

import math
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VINS = [("30", 3.0), ("36", 3.6), ("42", 4.2)]
LCS = [("nom", 1.0, 1.0), ("lmcm", 0.8, 0.8), ("lp", 1.2, 1.0), ("lm", 0.8, 1.0), ("lpcm", 1.2, 0.8)]
LOADS = [("lt", 0.1, 1.0), ("hv", 1.0, 1.4)]      # (code, load A, on-resistance factor)
L0, C0, RHS, RLS = 1e-6, 44e-6, 0.050, 0.030


def fmt(x, sig):
    if x == 0:
        return "0"
    digits = sig - 1 - math.floor(math.log10(abs(x)))
    return f"{round(x, digits):.{max(digits, 0)}f}"


def rtol_for(text):
    v = float(text)
    dec = len(text.split(".")[1]) if "." in text else 0
    return max(1e-3, 1.2 * 0.5 * 10 ** (-dec) / abs(v))


def simulate(path):
    r = subprocess.run(["ngspice", "-b", path.name], cwd=path.parent, capture_output=True, text=True, timeout=300)
    vals = {}
    for line in (r.stdout + r.stderr).splitlines():
        m = re.match(r"^\s*([A-Za-z_]\w*)\s*=\s*([-+0-9.eE]+)", line)
        if m:
            vals[m.group(1).lower()] = float(m.group(2))
    return vals


# ---------------------------------------------------------------------------------------------- netlist builders
def loop_netlist(vcode, vin):
    """Returns (netlist template, list of (meas name, key id, quantity, unit, scale, sig))."""
    rows, body, ctrl = [], [], ["op"]
    k = 0
    for lc, lf, cf in LCS:
        for ld, iload, rf in LOADS:
            k += 1
            tag = f"{lc}.{ld}"
            body.append(f"* {tag}: L = {lf:g} x 1 uH, C = {cf:g} x 44 uF, {iload:g} A, on-resistance x {rf:g}\n"
                        f"Vin{k} vin{k} 0 {vin}\n"
                        f"X{k} vin{k} o{k} f{k} buck_avg params: L={L0 * lf * 1e6:g}u C={C0 * cf * 1e6:g}u "
                        f"RHS={RHS * rf * 1e3:g}m RLS={RLS * rf * 1e3:g}m\n"
                        f"Vj{k} f{k} o{k} DC 0 AC 1\nIl{k} o{k} 0 DC {iload:g}\n")
            ctrl.append(f"let vo{k} = v(o{k})")
            rows += [(f"vo{k}", f"B.L{vcode}.{tag}.vo", f"DC output, {vin} V, {tag}", "V", 1, 5),
                     (f"fc{k}", f"B.L{vcode}.{tag}.fc", f"crossover, {vin} V, {tag}", "kHz", 1e-3, 3),
                     (f"pm{k}", f"B.L{vcode}.{tag}.pm", f"phase margin, {vin} V, {tag}", "°", 1, 3),
                     (f"gm{k}", f"B.L{vcode}.{tag}.gm", f"gain margin, {vin} V, {tag}", "dB", 1, 3)]
    ctrl.append("print " + " ".join(f"vo{i}" for i in range(1, k + 1)))
    ctrl.append("ac dec 200 100 10Meg")
    for i in range(1, k + 1):
        ctrl += [f"let t{i} = -v(o{i})/v(f{i})", f"let tdb{i} = db(t{i})", f"let tph{i} = 180/pi*cph(t{i})",
                 f"meas ac fc{i} when tdb{i}=0", f"meas ac phc{i} find tph{i} at=fc{i}",
                 f"meas ac fx{i} when tph{i}=-180 cross=last", f"meas ac gx{i} find tdb{i} at=fx{i}",
                 f"let pm{i} = 180 + phc{i}", f"let gm{i} = -gx{i}", f"print pm{i} gm{i}"]
    head = (f"* C1 option B: loop gain and DC output at {vin} V input, averaged model. Generated by gen_buck.py.\n"
            + "".join(f"* EXPECT {n} key:results.md#{kid} scale={1 / s:g} rtol={{rtol_{n}}}\n"
                      for n, kid, _, _, s, _ in rows)
            + ".include buck_avg.sub\n\n")
    return head + "\n".join(body) + "\n.control\n" + "\n".join(ctrl) + "\n.endc\n.end\n", rows


def step_netlist():
    rows, body, ctrl = [], [], ["tran 20n 400u"]
    k = 0
    for vcode, vin in VINS:
        for lc, lf, cf in (("nom", 1.0, 1.0), ("lpcm", 1.2, 0.8)):
            k += 1
            tag = f"{vcode}.{lc}"
            body.append(f"* {vin} V, L = {lf:g} x 1 uH, C = {cf:g} x 44 uF\nVin{k} vin{k} 0 {vin}\n"
                        f"X{k} vin{k} o{k} o{k} buck_avg params: L={L0 * lf * 1e6:g}u C={C0 * cf * 1e6:g}u\n"
                        f"Il{k} o{k} 0 PULSE(0.1 0.6 200u 100n 100n 1 2)\n")
            ctrl += [f"meas tran vp{k} find v(o{k}) at=199u", f"meas tran vm{k} min v(o{k}) from=200u to=300u",
                     f"meas tran tr{k} when v(o{k})=1.188 rise=1 from=200u",
                     f"let dev{k} = vp{k} - vm{k}", f"let rec{k} = tr{k} - 200u", f"print dev{k} rec{k}"]
            rows += [(f"dev{k}", f"B.S.{tag}.dev", f"load-step deviation, {vin} V, {lc}", "mV", 1e3, 3),
                     (f"rec{k}", f"B.S.{tag}.rec", f"recovery to within 1%, {vin} V, {lc}", "µs", 1e6, 3)]
    head = ("* C1 option B: 0.1 -> 0.6 A load step at each input voltage, averaged model. Generated by gen_buck.py.\n"
            + "".join(f"* EXPECT {n} key:results.md#{kid} scale={1 / s:g} rtol={{rtol_{n}}}\n"
                      for n, kid, _, _, s, _ in rows)
            + ".include buck_avg.sub\n\n")
    return head + "\n".join(body) + "\n.control\n" + "\n".join(ctrl) + "\n.endc\n.end\n", rows


SW_HEAD = ".include buck_sw.sub\nVramp ramp 0 PULSE(0 1 0 498n 2n 0 500n)\n.options reltol=1e-4\n\n"


def eff_netlist(iload):
    """One converter per netlist: three in one transient make the PWM comparators too stiff for the solver."""
    r = 1.2 / iload
    tag = f"{int(round(iload * 1000))}mA"
    rows = [("vo", f"B.E.{tag}.vo", f"output voltage, 3.6 V, {iload:g} A (switching)", "V", 1, 5),
            ("eta", f"B.E.{tag}.eta", f"efficiency, 3.6 V, {iload:g} A (switching)", "%", 1, 3)]
    body = f"Vin1 vin1 0 3.6\nX1 vin1 o1 o1 ramp buck_sw\nRl1 o1 0 {r:g}\n"
    ctrl = ["tran 1n 300u 0 2n uic", "meas tran vo avg v(o1) from=250u to=300u",
            "meas tran ii avg i(vin1) from=250u to=300u", f"let eta = 100 * (vo*vo/{r:g}) / (-ii*3.6)", "print eta"]
    head = (f"* C1 option B: efficiency and regulation at 3.6 V, {iload:g} A, switching model. Generated by gen_buck.py.\n"
            + "".join(f"* EXPECT {n} key:results.md#{kid} scale={1 / s:g} rtol={{rtol_{n}}}\n"
                      for n, kid, _, _, s, _ in rows) + SW_HEAD)
    return head + body + "\n.control\n" + "\n".join(ctrl) + "\n.endc\n.end\n", rows


def ripple_netlist():
    rows = [("vo", "B.R.vo", "output voltage, 4.2 V, 1 A, L -20%, C -20% (switching)", "V", 1, 5),
            ("rip", "B.R.rip", "output ripple, peak to peak", "mV", 1e3, 3),
            ("ipk", "B.R.ipk", "peak inductor current", "A", 1, 3),
            ("ivl", "B.R.ivl", "valley inductor current", "A", 1, 3)]
    body = ("Vin1 vin1 0 4.2\nX1 vin1 o1 o1 ramp buck_sw params: L=0.8u C=35.2u\nRl1 o1 0 1.2\n")
    ctrl = ["tran 1n 300u 0 2n uic", "meas tran vo avg v(o1) from=250u to=300u",
            "meas tran vx max v(o1) from=299.5u to=300u", "meas tran vn min v(o1) from=299.5u to=300u",
            "let rip = vx - vn", "meas tran ipk max i(v.x1.vil) from=299.5u to=300u",
            "meas tran ivl min i(v.x1.vil) from=299.5u to=300u", "print rip"]
    head = ("* C1 option B: ripple and peak current at 4.2 V, 1 A, L -20%, C -20%, switching model. "
            "Generated by gen_buck.py.\n"
            + "".join(f"* EXPECT {n} key:results.md#{kid} scale={1 / s:g} rtol={{rtol_{n}}}\n"
                      for n, kid, _, _, s, _ in rows) + SW_HEAD)
    return head + body + "\n.control\n" + "\n".join(ctrl) + "\n.endc\n.end\n", rows


def swstep_netlist(vcode, vin, lc="nom"):
    tag, desc = (vcode, "nominal") if lc == "nom" else (f"{vcode}.{lc}", "L +20%, C -20%")
    parts = "" if lc == "nom" else " params: L=1.2u C=35.2u"
    rows = [("dev", f"B.W.{tag}.dev", f"load-step deviation, {vin} V, {desc} (switching)", "mV", 1e3, 3),
            ("rec", f"B.W.{tag}.rec", f"recovery to within 1%, {vin} V, {desc} (switching)", "µs", 1e6, 3)]
    body = (f"Vin1 vin1 0 {vin}\nX1 vin1 o1 o1 ramp buck_sw{parts}\nRl1 o1 0 12\n"
            "Il1 o1 0 PULSE(0 0.5 250u 100n 100n 1 2)\n")
    ctrl = ["tran 1n 350u 0 2n uic", "meas tran vp avg v(o1) from=245u to=250u",
            "meas tran vm min v(o1) from=250u to=300u", "meas tran tr when v(o1)=1.188 rise=1 from=250u",
            "let dev = vp - vm", "let rec = tr - 250u", "print dev rec"]
    head = (f"* C1 option B: 0.1 -> 0.6 A load step at {vin} V, {desc}, switching model (12 ohm base load plus a "
            "0.5 A step). "
            "Generated by gen_buck.py.\n"
            + "".join(f"* EXPECT {n} key:results.md#{kid} scale={1 / s:g} rtol={{rtol_{n}}}\n"
                      for n, kid, _, _, s, _ in rows) + SW_HEAD)
    return head + body + "\n.control\n" + "\n".join(ctrl) + "\n.endc\n.end\n", rows


def main():
    run = "--run" in sys.argv
    published = {}
    if not run:
        text = (HERE / "results.md").read_text(encoding="utf-8")
        published = dict(re.findall(r"^\| (B\.[\w.-]+) \| [^|]+ \| ([-0-9.]+) \|", text, re.M))
    jobs = [(f"loop_v{c}.cir", *loop_netlist(c, v)) for c, v in VINS]
    jobs += [("step_avg.cir", *step_netlist()), *[(f"sw_eff_{int(round(i * 1000))}ma.cir", *eff_netlist(i)) for i in (0.1, 0.5, 1.0)], ("sw_ripple.cir", *ripple_netlist())]
    jobs += [(f"sw_step_v{c}.cir", *swstep_netlist(c, v)) for c, v in VINS]
    jobs += [("sw_step_v30_lpcm.cir", *swstep_netlist("30", 3.0, "lpcm"))]
    allrows = []
    for name, tmpl, rows in jobs:
        path = HERE / name
        if run:
            path.write_text(tmpl.format(**{f"rtol_{n}": "1e-3" for n, *_ in rows}), encoding="utf-8")
            vals = simulate(path)
            texts = {n: fmt(vals[n] * s, sig) for n, _, _, _, s, sig in rows}
        else:
            texts = {n: published[kid] for n, kid, *_ in rows}
        path.write_text(tmpl.format(**{f"rtol_{n}": f"{rtol_for(texts[n]):.1e}" for n, *_ in rows}), encoding="utf-8")
        allrows += [(kid, q, texts[n], u) for n, kid, q, u, _, _ in rows]
    if run:
        write_results(allrows)


def write_results(allrows):
    val = {kid: t for kid, _, t, _ in allrows}
    lines = ["# C1 Option B · Simulated Results", "",
             "Generated by [gen_buck.py](gen_buck.py) from the netlists in this folder; CI re-runs every netlist and "
             "checks it against the answer key below (`tools/run_spice.py`). The design is in "
             "[design-report.md](design-report.md).", "",
             "## Loop gain and regulation (averaged model)", "",
             "Light load is 0.1 A with 27 °C on-resistance; full load is 1 A with on-resistance +40% (125 °C). "
             "$L$ and $C$ are 1 µH and 44 µF nominal.", "",
             "| Input | L, C | Load | DC output (V) | Crossover (kHz) | Phase margin (°) | Gain margin (dB) |",
             "|---|---|---|---|---|---|---|"]
    names = {"nom": "nominal", "lmcm": "L −20%, C −20%", "lp": "L +20%", "lm": "L −20%", "lpcm": "L +20%, C −20%"}
    for vcode, vin in VINS:
        for lc, _, _ in LCS:
            for ld, iload, _ in LOADS:
                p = f"B.L{vcode}.{lc}.{ld}"
                lines.append(f"| {vin} V | {names[lc]} | {'0.1 A, 27 °C' if ld == 'lt' else '1 A, 125 °C'} | "
                             f"{val[p + '.vo']} | {val[p + '.fc']} | {val[p + '.pm']} | {val[p + '.gm']} |")
    lines += ["", "## Load step 0.1 A → 0.6 A in 100 ns (averaged model)", "",
              "| Input | L, C | Deviation (mV) | Recovery to within 1% (µs) |", "|---|---|---|---|"]
    for vcode, vin in VINS:
        for lc in ("nom", "lpcm"):
            p = f"B.S.{vcode}.{lc}"
            lines.append(f"| {vin} V | {names[lc]} | {val[p + '.dev']} | {val[p + '.rec']} |")
    lines += ["", "## Switching model", "",
              "| Condition | Output (V) | Result |", "|---|---|---|",
              f"| 3.6 V, 0.1 A | {val['B.E.100mA.vo']} | efficiency {val['B.E.100mA.eta']}% |",
              f"| 3.6 V, 0.5 A | {val['B.E.500mA.vo']} | efficiency {val['B.E.500mA.eta']}% |",
              f"| 3.6 V, 1 A | {val['B.E.1000mA.vo']} | efficiency {val['B.E.1000mA.eta']}% |",
              f"| 4.2 V, 1 A, L −20%, C −20% | {val['B.R.vo']} | ripple {val['B.R.rip']} mV p-p; inductor current "
              f"{val['B.R.ivl']} to {val['B.R.ipk']} A |",
              *[f"| {vin} V, step 0.1 → 0.6 A | — | deviation {val[f'B.W.{c}.dev']} mV; recovery {val[f'B.W.{c}.rec']} µs |"
                for c, vin in VINS],
              f"| 3.0 V, L +20%, C −20%, step 0.1 → 0.6 A | — | deviation {val['B.W.30.lpcm.dev']} mV; recovery "
              f"{val['B.W.30.lpcm.rec']} µs |",
              "", "<!-- answer-key -->", "", "| ID | Quantity | Value | Unit |", "|---|---|---|---|"]
    lines += [f"| {kid} | {q} | {t} | {u} |" for kid, q, t, u in allrows]
    (HERE / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
