#!/usr/bin/env python3
"""Build reference/glossary.md from reference/glossary.yml.

Each YAML entry:
    - term: Phasor
      definition: A complex number that encodes ...
      chapter: "02-01"            # chapter where the term is first defined
      anchor: phasor              # optional; default = slug(term)
      see_also: [Impedance]       # optional; other terms in the glossary

Chapters link to terms as  ../../../reference/glossary.md#<anchor>.

Usage:
    python tools/build_glossary.py          # write reference/glossary.md
    python tools/build_glossary.py --check  # exit 1 if stale or invalid
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "reference" / "glossary.yml"
OUT = ROOT / "reference" / "glossary.md"


def slug(term: str) -> str:
    s = term.lower().replace("'", "").replace("’", "")
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")


def chapter_paths() -> dict[str, str]:
    cur = yaml.safe_load((ROOT / "tools" / "data" / "curriculum.yml").read_text(encoding="utf-8"))
    out = {}
    for c in cur["courses"]:
        for ch in c["chapters"]:
            out[ch["id"]] = f"../courses/{c['id']}-{c['slug']}/chapters/{ch['id']}-{ch['slug']}.md"
    return out


def build() -> str:
    entries = yaml.safe_load(SRC.read_text(encoding="utf-8")) or []
    paths = chapter_paths()
    errors = []
    by_anchor = {}
    by_term = {}
    for e in entries:
        a = e.get("anchor") or slug(e["term"])
        e["anchor"] = a
        if a in by_anchor:
            errors.append(f"duplicate anchor {a} ({e['term']} / {by_anchor[a]['term']})")
        by_anchor[a] = e
        by_term[e["term"].lower()] = e
        if e.get("chapter") and e["chapter"] not in paths:
            errors.append(f"{e['term']}: unknown chapter {e['chapter']}")
    for e in entries:
        for s in e.get("see_also", []) or []:
            if s.lower() not in by_term:
                errors.append(f"{e['term']}: see_also '{s}' is not a glossary term")
    if errors:
        sys.exit("glossary.yml errors:\n  " + "\n  ".join(errors))

    entries.sort(key=lambda e: e["term"].lower())
    letters = []
    for e in entries:
        L = e["term"][0].upper()
        L = L if L.isalpha() else "#"
        if L not in letters:
            letters.append(L)
    out = ["# Glossary", "",
           "<!-- GENERATED by tools/build_glossary.py from reference/glossary.yml — edit the YAML, not this file -->",
           "",
           f"{len(entries)} terms. Each entry links to the chapter where the term is first defined. "
           "Notation follows [notation.md](notation.md).", ""]
    if letters:
        out.append(" · ".join(f"[{L}](#letter-{L.lower() if L != '#' else 'other'})" for L in letters))
        out.append("")
    current = None
    for e in entries:
        L = e["term"][0].upper()
        L = L if L.isalpha() else "#"
        if L != current:
            current = L
            lid = L.lower() if L != "#" else "other"
            out += [f'<a id="letter-{lid}"></a>', "", f"## {L}", ""]
        definition = e["definition"].strip().replace("*", "\\*")  # z* must not start emphasis
        line = f'<a id="{e["anchor"]}"></a>**{e["term"]}** — {definition}'
        if e.get("chapter"):
            line += f" *First defined in* [{e['chapter']}]({paths[e['chapter']]})."
        if e.get("see_also"):
            refs = ", ".join(f"[{s}](#{by_term[s.lower()]['anchor']})" for s in e["see_also"])
            line += f" *See also:* {refs}."
        out += [line, ""]
    return "\n".join(out)


def main() -> int:
    text = build()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if "--check" in sys.argv:
        if current != text:
            print("reference/glossary.md is stale; run `python tools/build_glossary.py`")
            return 1
        print("glossary: up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"glossary: wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
