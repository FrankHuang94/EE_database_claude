#!/usr/bin/env python3
"""Generate the practitioner question banks from the chapters' Practitioner lens sections.

Every chapter's section 9 carries a "Marketing vs Reality" block and "Questions for engineering leaders" with
strong and evasive answers. This script collects both from every chapter that is not a planned stub, groups them
by domain, rewrites relative links so they still resolve from practitioner/question-banks/, and writes one file
per domain plus an index.

Usage:
    python tools/build_practitioner.py          # write the files
    python tools/build_practitioner.py --check  # exit 1 if any generated file is stale (CI)
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "practitioner" / "question-banks"
HEADER = ("<!-- generated by tools/build_practitioner.py from each chapter's Practitioner lens; "
          "edit the chapters, not this file -->")

# domain slug, title, the courses it collects, and the playbook that uses it
DOMAINS = [
    ("foundations", "Foundations: Math, Physics, Circuits, Signals and Control",
     ["00", "01", "02", "03", "04", "05", "06", "07", "11", "15", "16"]),
    ("digital-and-computing", "Digital Logic, Computer Architecture and VLSI", ["08", "14", "19"]),
    ("devices-and-manufacturing", "Devices, Fabrication, Packaging, Test and Reliability", ["09", "25"]),
    ("analog-and-mixed-signal", "Analog and Mixed-Signal Circuits", ["10", "12", "20"]),
    ("rf-and-wireless", "Electromagnetics, Communications and RF", ["13", "17", "21"]),
    ("embedded", "Embedded Systems and Microcontrollers", ["18"]),
    ("power", "Power Electronics and Energy Conversion", ["22"]),
    ("memory", "Memory and Storage", ["23"]),
    ("interconnect-and-photonics", "High-Speed I/O, Signal Integrity and Photonics", ["24"]),
    ("systems-and-business", "Design Practice, System Architectures and Diligence", ["26", "27", "28"]),
]

STATUS_RE = re.compile(r"<!--\s*status:\s*([a-z-]+)\s*-->")
TITLE_RE = re.compile(r"^# (\d\d-\d\d) · (.+)$", re.M)
# A block starts at its label: a heading, or a bold label at column 0 that may run on into text on the same line
# ("**Questions for engineering leaders.** The banks in ..."). Group 1 is that run-on text.
Q_HEAD = re.compile(r"^(?:#{3,4} Questions (?:for|to ask)[^\n]*|\*\*Questions (?:for|to ask) engineering leaders\.?\*\*)"
                    r"[ \t]*([^\n]*)$", re.M)
M_HEAD = re.compile(r"^(?:#{3,4} Marketing vs\.? Reality[^\n]*|\*\*Marketing vs\.? Reality\.?\*\*)[ \t]*([^\n]*)$", re.M)
# A block ends at the next heading or at the next section-9 label; other bold paragraphs (claims) belong to it.
STOP_RE = re.compile(r"^(?:#{2,4} |\*\*(?:Marketing vs\.? Reality|Questions (?:for|to ask)|State of the art|State of play|"
                     r"Why it matters commercially|Commercial relevance))")
CLAIM_RE = re.compile(r'^\*\*["“]')
LINK_RE = re.compile(r"(!?\[[^\]]*\])\(([^)\s]+)\)")


def section9(text):
    m = re.search(r"^## 9\. Practitioner lens.*?$(.*?)(?=^## 10\.)", text, re.M | re.S)
    return m.group(1) if m else ""


def block_after(sec, head_re):
    """The block a label starts: its run-on text, then every line up to the next heading or section-9 label."""
    m = head_re.search(sec)
    if not m:
        return ""
    out = [m.group(1)] if m.group(1).strip() else []
    for line in sec[m.end():].split("\n")[1:]:
        if STOP_RE.match(line):
            break
        out.append(line)
    return "\n".join(out).strip("\n")


def lost_claims(chapters):
    """Quoted claims (bold, starting with a quotation mark) in a section 9 that its extracted blocks do not contain."""
    lost = []
    for key, (f, _, mvr, qs) in chapters.items():
        sec = section9(f.read_text(encoding="utf-8"))
        for line in sec.split("\n"):
            if CLAIM_RE.match(line) and line.strip() not in mvr and line.strip() not in qs:
                lost.append(f"{key}: {line[:70]}")
    return lost


KEY_PTR = re.compile(r" \((?:Txt|Ex) [0-9a-z.-]{1,12}\)")   # in-text pointers to a chapter's answer-key IDs


def rewrite_links(md, chapter: Path, out_dir: Path):
    def fix(m):
        label, target = m.group(1), m.group(2)
        if re.match(r"^[a-z]+:", target):
            return m.group(0)
        path, _, anchor = target.partition("#")
        src = chapter if path == "" else (chapter.parent / path).resolve()
        rel = os.path.relpath(src, out_dir).replace(os.sep, "/")
        return f"{label}({rel}{'#' + anchor if anchor else ''})"
    return KEY_PTR.sub("", LINK_RE.sub(fix, md))


def collect():
    chapters = {}
    for f in sorted((ROOT / "courses").glob("*/chapters/*.md")):
        text = f.read_text(encoding="utf-8")
        st = STATUS_RE.search(text)
        t = TITLE_RE.search(text)
        if not st or st.group(1) == "planned" or not t:
            continue
        sec = section9(text)
        chapters[t.group(1)] = (f, t.group(2).strip(), block_after(sec, M_HEAD), block_after(sec, Q_HEAD))
    return chapters


def course_titles():
    titles = {}
    for d in sorted((ROOT / "courses").iterdir()):
        r = d / "README.md"
        if r.exists():
            m = re.search(r"^# (.+)$", r.read_text(encoding="utf-8"), re.M)
            titles[d.name[:2]] = (d.name, m.group(1).strip() if m else d.name)
    return titles


def count_questions(q):
    return len(re.findall(r"^\d+\. ", q, re.M))


def render(chapters, titles):
    files, index_rows, total_q, total_c = {}, [], 0, 0
    for slug, title, courses in DOMAINS:
        out = OUT / f"{slug}.md"
        body, nq, nc = [], 0, 0
        for cid in courses:
            mine = [(k, v) for k, v in chapters.items() if k.startswith(cid + "-")]
            if not mine:
                continue
            cdir, ctitle = titles[cid]
            readme = os.path.relpath(ROOT / "courses" / cdir / "README.md", OUT).replace(os.sep, "/")
            body += [f"## [{ctitle}]({readme})", ""]
            for key, (f, ctitle_ch, mvr, qs) in mine:
                rel = os.path.relpath(f, OUT).replace(os.sep, "/")
                body += [f"### [{key} · {ctitle_ch}]({rel})", ""]
                if mvr:
                    body += ["**Marketing vs Reality.**", "", rewrite_links(mvr, f, OUT), ""]
                if qs:
                    body += ["**Questions for engineering leaders.**", "", rewrite_links(qs, f, OUT), ""]
                    nq += count_questions(qs)
                if not mvr and not qs:
                    body += ["*This chapter's Practitioner lens has no Marketing vs Reality block or question list; "
                             "read the chapter directly.*", ""]
                nc += 1
        head = [HEADER, f"# Question Bank · {title}", "",
                f"{nc} chapters and {nq} questions, collected from each chapter's Practitioner lens (section 9). "
                "Each block keeps the chapter's own wording, dates and tags; a bare number in brackets, such as [2], "
                "cites that chapter's Sources list, and an R-number cites the "
                "[research log](../../reference/research-log.md). Perishable facts are as of the date the chapter "
                "states. The [playbooks](../playbooks/README.md) say which questions to ask first.", ""]
        text = "\n".join(head + body).rstrip("\n") + "\n"
        text = re.sub(r"\n{3,}", "\n\n", text)
        files[out] = text
        index_rows.append(f"| [{title}]({slug}.md) | {', '.join(courses)} | {nc} | {nq} |")
        total_q += nq
        total_c += nc
    index = [HEADER, "# Question Banks", "",
             "Every chapter ends its Practitioner lens with a **Marketing vs Reality** box and questions for "
             "engineering leaders, each with what a strong and an evasive answer sound like. These files collect them "
             "by domain, regenerated from the chapters on every change. Start from the matching "
             "[playbook](../playbooks/README.md), which picks the questions that decide a deal, then use the bank "
             "for depth.", "",
             "| Domain | Courses | Chapters | Questions |", "|---|---|---|---|", *index_rows,
             f"| **Total** | | **{total_c}** | **{total_q}** |", ""]
    files[OUT / "README.md"] = "\n".join(index)
    return files


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    chapters = collect()
    lost = lost_claims(chapters)
    if lost:
        print("build_practitioner: claims missing from the extracted blocks:\n  " + "\n  ".join(lost))
        return 1
    files = render(chapters, course_titles())
    stale = []
    for path, text in files.items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if args.check and stale:
        print("build_practitioner: stale: " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return 1
    print(f"build_practitioner: {'checked' if args.check else 'wrote'} {len(files)} files"
          + (f" ({len(stale)} changed)" if not args.check else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
