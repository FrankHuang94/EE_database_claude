#!/usr/bin/env python3
"""Regenerate squint.cir: a 16-element receive array (lambda/2 at 28 GHz, steered to 60 degrees) built twice,
with fixed phase shifters and with true-time delay, summed by VCCS into 1 ohm.

Each element path is modelled with matched 50 ohm lossless lines. The free-space delay of element k relative to
the last element is (N-1-k)*tg with tg = d*sin(theta0)/c. A phase shifter is frequency independent, so it is
placed (by linearity) as the fixed phase of the element's AC source; true-time delay is a second line of delay
k*tg that equalizes every path at every frequency."""
import math
from pathlib import Path

N, F0, TH0 = 16, 28e9, 60.0
TG = math.sin(math.radians(TH0)) / (2 * F0)          # d = lambda0/2, so d*sin(theta0)/c = sin(theta0)/(2 f0)
KEY = "key:../../chapters/21-10-antennas-arrays-mmwave.md#"

lines = [
    "* Lab 21-10: beam squint of a 16-element receive array, phase shifters vs true-time delay (Example 21-10.4)",
    "* Elements spaced lambda/2 at 28 GHz, beam steered to 60 degrees. Path k carries the free-space delay",
    "* (N-1-k)*tg (tg = d sin(theta0)/c) as a matched 50 ohm line. Phase-shifter array: each element's fixed",
    "* phase -360*f0*k*tg is set at 28 GHz and does not change with frequency. TTD array: a second line of delay",
    "* k*tg equalizes every path at all frequencies. VCCS sum the 16 line outputs into 1 ohm.",
    f"* Generated by gen_squint.py; tg = {TG:.6e} s.",
    f"* EXPECT lps26 {KEY}Ex_21-10.4e rtol=2e-3",
    f"* EXPECT lps30 {KEY}Ex_21-10.4e rtol=2e-3",
    f"* EXPECT gttd26 {KEY}Ex_21-10.4g rtol=1e-3",
    "",
]
for arr in ("ps", "ttd"):
    for k in range(N):
        ph = -360 * F0 * k * TG if arr == "ps" else 0.0
        ph = ((ph + 180) % 360) - 180
        lines += [f"V{arr}{k} s{arr}{k} 0 dc 0 ac 1 {ph:.6f}", f"R{arr}s{k} s{arr}{k} a{arr}{k} 50"]
        d1 = (N - 1 - k) * TG
        mid = f"e{arr}{k}" if arr == "ps" else f"m{arr}{k}"
        lines.append(f"T{arr}{k} a{arr}{k} 0 {mid} 0 Z0=50 TD={d1:.9e}" if d1 > 0 else f"R{arr}w{k} a{arr}{k} {mid} 1e-6")
        if arr == "ttd":
            d2 = k * TG
            lines.append(f"T{arr}c{k} {mid} 0 e{arr}{k} 0 Z0=50 TD={d2:.9e}" if d2 > 0
                         else f"R{arr}c{k} {mid} e{arr}{k} 1e-6")
        lines += [f"R{arr}l{k} e{arr}{k} 0 50", f"G{arr}{k} 0 out{arr} e{arr}{k} 0 1"]
    lines += [f"Rout{arr} out{arr} 0 1", ""]
lines += [".control", "ac lin 5 26G 30G",
          "let lps = db(v(outps)) - db(v(outttd))",
          "let gttd = db(v(outttd)/0.5)",
          "meas ac lps26 find lps at=26e9", "meas ac lps28 find lps at=28e9", "meas ac lps30 find lps at=30e9",
          "meas ac gttd26 find gttd at=26e9", "meas ac gttd30 find gttd at=30e9",
          ".endc", ".end"]
Path(__file__).with_name("squint.cir").write_text("\n".join(lines) + "\n")
