#!/usr/bin/env python3
"""Write the PVT-corner netlists for the C1 option A op-amp and, with --run, simulate them and write results.md.

Each corner netlist holds three copies of the op-amp, each on its own supply so its power can be read:
  A  open-loop AC response (DC loop closed through 1 GH, inverting input AC-grounded through 1 F): A0, UGF, PM,
     supply power, and the tail transistor's saturation margin V_DS - V_DSAT at V_CM = 0.9 V;
  B  unity-gain follower driven by a 0.6 -> 1.2 V step: slew rate on both edges, measured from 20% to 80%;
  C  inverting gain of -1 (100 kOhm / 100 kOhm about 0.9 V): the output range over which the closed-loop gain stays
     within 1% of -1.
The TT netlist also measures CMRR, PSRR+ and the input-referred noise at 1 MHz (tt_extra.cir).
Every measurement is tied to results.md by an EXPECT line, so CI (tools/run_spice.py) re-runs the corners.

Usage:  python gen_corners.py          # rewrite the netlists only
        python gen_corners.py --run    # rewrite, simulate with ngspice and rewrite results.md
"""
from __future__ import annotations

import math
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "corners"
CORNERS = [  # (id, process, temperature degC, VDD V)
    ("SS-C", "ss", -40, 1.98), ("SS-N", "ss", 27, 1.80), ("SS-H", "ss", 125, 1.62),
    ("TT-C", "tt", -40, 1.98), ("TT-N", "tt", 27, 1.80), ("TT-H", "tt", 125, 1.62),
    ("FF-C", "ff", -40, 1.98), ("FF-N", "ff", 27, 1.80), ("FF-H", "ff", 125, 1.62),
    ("SF-N", "sf", 27, 1.80), ("FS-N", "fs", 27, 1.80),
]
MEAS = [  # (name, quantity, unit, scale from SPICE units to published units, significant figures)
    ("a0", "open-loop DC gain", "dB", 1, 3),
    ("ugf", "unity-gain frequency", "MHz", 1e-6, 3),
    ("pm", "phase margin", "°", 1, 3),
    ("srr", "slew rate, rising", "V/µs", 1, 3),
    ("srf", "slew rate, falling", "V/µs", 1, 3),
    ("pwr", "supply power", "µW", 1e6, 3),
    ("outhi", "output high (1% gain error)", "V", 1, 4),
    ("outlo", "output low (1% gain error)", "V", 1, 3),
    ("m5mar", "tail V_DS - V_DSAT at V_CM = 0.9 V", "mV", 1e3, 3),
]


def netlist(cid, proc, temp, vdd):
    expects = "\n".join(
        f"* EXPECT {n} key:../results.md#A.{cid}.{n} scale={1 / s:g} rtol={{rtol_{n}}}" for n, _, _, s, _ in MEAS)
    return f"""* C1 option A, corner {cid}: process {proc.upper()}, {temp} degC, VDD = {vdd} V. Generated by gen_corners.py.
{expects}
.lib '../../models/c1_process.lib' {proc}
.include ../opamp.sub
.temp {temp}

* A: open-loop response
VDDA vdda 0 {vdd}
IRA vdda iba 20u
VINA pa 0 DC 0.9 AC 1
XA pa na oa vdda 0 iba opamp
LFA oa na 1G
CFA na 0 1
CLA oa 0 2p

* B: unity-gain follower, slew rate
VDDB vddb 0 {vdd}
IRB vddb ibb 20u
VSB pb 0 PULSE(0.6 1.2 100n 1n 1n 400n 800n)
XB pb ob ob vddb 0 ibb opamp
CLB ob 0 2p

* C: inverting gain of -1 about 0.9 V, output range
VDDC vddc 0 {vdd}
IRC vddc ibc 20u
VRC rc 0 0.9
VSC sc 0 0.9
R1C sc nc 100k
R2C nc oc 100k
XC rc nc oc vddc 0 ibc opamp
CLC oc 0 2p

.control
op
let pwr = -i(vdda) * {vdd}
let m5mar = @m.xa.m5[vds] - @m.xa.m5[vdsat]
print pwr m5mar
ac dec 50 1 10G
meas ac a0 find vdb(oa) at=10
meas ac ugf when vdb(oa)=0
meas ac pha find vp(oa) at=ugf
let pm = 180 + pha * 180 / pi
print pm
tran 0.1n 1000n
meas tran tr1 when v(ob)=0.72 rise=1
meas tran tr2 when v(ob)=1.08 rise=1
meas tran tf1 when v(ob)=1.08 fall=1
meas tran tf2 when v(ob)=0.72 fall=1
let srr = 0.36 / (tr2 - tr1) / 1e6
let srf = 0.36 / (tf2 - tf1) / 1e6
print srr srf
dc vsc -0.6 2.2 0.001
let gcl = -deriv(v(oc))
meas dc va when gcl=0.99 rise=1
meas dc vb when gcl=0.99 fall=1
let outhi = 1.8 - va
let outlo = 1.8 - vb
print outhi outlo
.endc
.end
"""


TT_EXTRA = """* C1 option A at TT, 27 degC, 1.8 V: CMRR, PSRR+ and input-referred noise. Generated by gen_corners.py.
* EXPECT cmrr key:results.md#A.TT-N.cmrr rtol={rtol_cmrr}
* EXPECT psrr key:results.md#A.TT-N.psrr rtol={rtol_psrr}
* EXPECT vn1m key:results.md#A.TT-N.vn1m scale=1e-9 rtol={rtol_vn1m}
.lib '../models/c1_process.lib' tt
.include opamp.sub

* differential gain
VDD1 vdd1 0 1.8
IR1 vdd1 ib1 20u
VI1 p1 0 DC 0.9 AC 1
X1 p1 n1 o1 vdd1 0 ib1 opamp
L1 o1 n1 1G
C1 n1 0 1
CL1 o1 0 2p
* common-mode gain: the inverting input follows the AC source through 1 F
VDD2 vdd2 0 1.8
IR2 vdd2 ib2 20u
VI2 p2 0 DC 0.9 AC 1
X2 p2 n2 o2 vdd2 0 ib2 opamp
L2 o2 n2 1G
C2 n2 p2 1
CL2 o2 0 2p
* supply gain: AC on VDD
VDD3 vdd3 0 DC 1.8 AC 1
IR3 vdd3 ib3 20u
VI3 p3 0 DC 0.9
X3 p3 n3 o3 vdd3 0 ib3 opamp
L3 o3 n3 1G
C3 n3 0 1
CL3 o3 0 2p

.control
ac dec 20 1 1G
meas ac adm find vdb(o1) at=10
meas ac acm find vdb(o2) at=10
meas ac avdd find vdb(o3) at=10
let cmrr = adm - acm
let psrr = adm - avdd
print cmrr psrr
noise v(o1) vi1 dec 20 1k 100meg
setplot noise1
let vn1m = inoise_spectrum[60]
print vn1m
.endc
.end
"""
EXTRA = [("cmrr", "CMRR at 10 Hz", "dB", 1, 3), ("psrr", "PSRR+ at 10 Hz", "dB", 1, 3),
         ("vn1m", "input-referred noise at 1 MHz", "nV/√Hz", 1e9, 3)]


def fmt(x, sig):
    """Round to sig significant figures and return the string (no exponent for these ranges)."""
    if x == 0:
        return "0"
    digits = sig - 1 - math.floor(math.log10(abs(x)))
    return f"{round(x, digits):.{max(digits, 0)}f}"


def rtol_for(text):
    """Relative tolerance that covers rounding to the published digits (at least 1e-3)."""
    v = float(text)
    dec = len(text.split(".")[1]) if "." in text else 0
    return max(1e-3, 1.2 * 0.5 * 10 ** (-dec) / abs(v))


def simulate(path):
    r = subprocess.run(["ngspice", "-b", path.name], cwd=path.parent, capture_output=True, text=True, timeout=300)
    vals = {}
    for line in (r.stdout + r.stderr).splitlines():
        m = re.match(r"^\s*([A-Za-z_]\w*)\s*=\s*([-+0-9.eE]+)", line)
        if m:
            vals[m.group(1).lower()] = float(m.group(2))
    return vals


def main():
    OUT.mkdir(exist_ok=True)
    run = "--run" in sys.argv
    published = {}
    if not run:  # reuse the published values to fill in the tolerances
        text = (HERE / "results.md").read_text(encoding="utf-8")
        published = dict(re.findall(r"^\| (A\.[\w.-]+) \| [^|]+ \| ([-0-9.]+) \|", text, re.M))
    rows = []
    for cid, proc, temp, vdd in CORNERS:
        path = OUT / f"{cid.lower()}.cir"
        if run:
            path.write_text(netlist(cid, proc, temp, vdd).replace("{rtol_", "{{rtol_"), encoding="utf-8")
            path.write_text(netlist(cid, proc, temp, vdd).format(**{f"rtol_{n}": "1e-3" for n, *_ in MEAS}),
                            encoding="utf-8")
            vals = simulate(path)
            texts = {n: fmt(vals[n] * s, sig) for n, _, _, s, sig in MEAS}
        else:
            texts = {n: published[f"A.{cid}.{n}"] for n, *_ in MEAS}
        path.write_text(netlist(cid, proc, temp, vdd).format(**{f"rtol_{n}": f"{rtol_for(texts[n]):.1e}"
                                                                for n, *_ in MEAS}), encoding="utf-8")
        rows.append((cid, proc, temp, vdd, texts))
    path = HERE / "tt_extra.cir"
    if run:
        path.write_text(TT_EXTRA.format(**{f"rtol_{n}": "1e-3" for n, *_ in EXTRA}), encoding="utf-8")
        vals = simulate(path)
        extra = {n: fmt(vals[n] * s, sig) for n, _, _, s, sig in EXTRA}
    else:
        extra = {n: published[f"A.TT-N.{n}"] for n, *_ in EXTRA}
    path.write_text(TT_EXTRA.format(**{f"rtol_{n}": f"{rtol_for(extra[n]):.1e}" for n, *_ in EXTRA}), encoding="utf-8")
    if run:
        write_results(rows, extra)


def write_results(rows, extra):
    lines = ["# C1 Option A · Simulated Results at the PVT Corners", "",
             "Generated by [gen_corners.py](gen_corners.py) from the netlists in [corners/](corners/) and "
             "[tt_extra.cir](tt_extra.cir); CI re-runs every netlist and checks it against the answer key below "
             "(`tools/run_spice.py`). The design is in [design-report.md](design-report.md).", "",
             "Corners: process SS, TT, FF with (temperature, supply) cold-high (−40 °C, 1.98 V), nominal (27 °C, 1.80 V) "
             "and hot-low (125 °C, 1.62 V); SF and FS at nominal. Load 2 pF; input common mode 0.9 V; 20 µA reference.",
             "", "| Corner | A0 (dB) | UGF (MHz) | PM (°) | SR+ (V/µs) | SR− (V/µs) | Power (µW) | Out high (V) "
             "| Out low (V) | Tail margin (mV) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for cid, proc, temp, vdd, t in rows:
        lines.append(f"| {cid} ({proc.upper()}, {temp} °C, {vdd:.2f} V) | " + " | ".join(t[n] for n, *_ in MEAS) + " |")
    lines += ["", f"At TT, 27 °C, 1.8 V: CMRR {extra['cmrr']} dB and PSRR+ {extra['psrr']} dB at 10 Hz; input-referred "
              f"noise {extra['vn1m']} nV/√Hz at 1 MHz (thermal only: the C1 models have no flicker noise).", "",
              "<!-- answer-key -->", "", "| ID | Quantity | Value | Unit |", "|---|---|---|---|"]
    for cid, proc, temp, vdd, t in rows:
        for n, q, u, _, _ in MEAS:
            lines.append(f"| A.{cid}.{n} | {q}, {cid} | {t[n]} | {u} |")
    for n, q, u, _, _ in EXTRA:
        lines.append(f"| A.TT-N.{n} | {q}, TT-N | {extra[n]} | {u} |")
    (HERE / "results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
